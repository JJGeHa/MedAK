/**
 * Generates a VBA module that fills SKAT's AKSA 2278 Excel template with a golden test case
 * and opens the template's own "Dan fil" dialog, so the expected output can be produced by
 * SKAT's code. See docs/testing.md for how to run it.
 */
import { encodeWindows1252 } from "../../src/encoding.ts";
import { FIELDS } from "../../src/fields.ts";
import { GOLDEN_CASES, type GoldenCase, type Template } from "./cases.ts";

/** Excel column number for each field: the template's columns follow the field order. */
const COLUMNS = FIELDS.filter((f) => f.key !== "FILLER").map((f, i) => [f.key, i + 1] as const);

/** First data row in the template's "AKSA 2278" sheet. */
const FIRST_ROW = 4;

const vbaString = (s: string) => `"${s.replaceAll('"', '""')}"`;
export const macroName = (c: GoldenCase) => "MedAK_" + c.id.replace(/[^A-Za-z0-9]/g, "_");

function caseMacro(c: GoldenCase): string[] {
  const lines = [
    `Public Sub ${macroName(c)}()`,
    `    ' ${c.description}`,
    `    ' Save the file as ${c.id}.txt in packages/engine/test/golden/expected/`,
    `    Dim ws As Worksheet`,
    `    Set ws = MedAKStart(${vbaString(c.scenario)})`,
  ];
  c.rows.forEach((row, i) => {
    for (const [key, col] of COLUMNS) {
      const value = row[key];
      if (value !== undefined && value !== "") {
        lines.push(`    ws.Cells(${FIRST_ROW + i}, ${col}).Value = ${vbaString(value)}`);
      }
    }
  });
  lines.push(
    `    MedAKFinish ws, ${vbaString(c.sender.seNumber)}, ${vbaString(c.sender.name)}, ${vbaString(c.sender.address)}`,
    `End Sub`,
    ``,
  );
  return lines;
}

const COMMON = `Attribute VB_Name = "MedAKGolden"
' Generated by scripts/golden/make-harness.ts from packages/engine/test/golden/cases.ts.
' Do not edit by hand. Import into SKAT's template (Alt+F11, File > Import File), then run
' one MedAK_... macro per case (Alt+F8). See docs/testing.md.
Option Explicit

' Choose the scenario the way the intro sheet's buttons do, then unlock and clear the sheet.
' Events are switched off so the cells hold exactly the test values (no auto-fill).
Private Function MedAKStart(scenario As String) As Worksheet
    Select Case scenario
        Case "A": CollectionControl.ClickOptionA
        Case "B": CollectionControl.ClickOptionB
        Case "C": CollectionControl.ClickOptionC
        Case "D": CollectionControl.ClickOptionD
    End Select
    Application.EnableEvents = False
    Dim ws As Worksheet
    Set ws = ThisWorkbook.Worksheets("AKSA 2278")
    ws.Unprotect
    ws.Range("A4:BJ10004").ClearContents
    ws.Range("A4:BJ10004").NumberFormat = "@"
    Set MedAKStart = ws
End Function

' Pre-fill the sender in the cells the "Dan fil" dialog reads, then open the dialog.
Private Sub MedAKFinish(ws As Worksheet, se As String, nm As String, adr As String)
    ws.Activate
    FindGemBogstav
    ws.Range(gemBogstav & "5:" & gemBogstav & "7").NumberFormat = "@"
    ws.Range(gemBogstav & "5").Value = se
    ws.Range(gemBogstav & "6").Value = nm
    ws.Range(gemBogstav & "7").Value = adr
    ws.Protect
    Application.EnableEvents = True
    DanFil_Click
End Sub

`;

/** The harness module for one template, as Windows-1252 bytes with CRLF line endings. */
export function makeHarness(template: Template): Uint8Array {
  const cases = GOLDEN_CASES.filter((c) => c.template === template);
  const text = COMMON + cases.flatMap(caseMacro).join("\n");
  return encodeWindows1252(text.replace(/\r?\n/g, "\r\n"));
}

export const TEMPLATES: readonly Template[] = ["salg-af-aktier", "likvidationsprovenu"];
export const harnessFileName = (t: Template) => `harness-${t}.bas`;
